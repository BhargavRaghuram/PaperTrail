"""Scenario definitions for PaperTrail synthetic test data.
All people, vehicles, registration numbers, chassis numbers, insurers and dealers are FICTIONAL.
RTO code 99 is used deliberately because it does not exist in the states used."""
from datetime import date, timedelta

def d(s): return date.fromisoformat(s)

def annual_policies(starts, insurer, prefix, ncb=None):
    """Build 1-year policies from a list of start dates (end = start + 1y - 1d)."""
    out = []
    for i, s in enumerate(starts):
        sd = d(s)
        try: ed = sd.replace(year=sd.year + 1) - timedelta(days=1)
        except ValueError: ed = sd.replace(year=sd.year + 1, day=28)
        out.append(dict(policy_number=f"{prefix}{sd.year}{7310+i*17:05d}", insurer=insurer,
                        start=sd.isoformat(), end=ed.isoformat(),
                        ncb_percent=(ncb[i] if ncb else [20,25,35,45,50,50,50][min(i,6)])))
    return out

